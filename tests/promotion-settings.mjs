import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';

const modules = new Map();
function load(name) {
  if (name === './overlay-view') return { overlaysPage: () => '' };
  const file = `src/${name.replace(/^\.\//, '')}.ts`;
  if (modules.has(file)) return modules.get(file);
  const exports = {};
  modules.set(file, exports);
  const source = fs.readFileSync(file, 'utf8').replaceAll('import.meta.url', '"file:///app/src/views.ts"');
  vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports, require: load, URL });
  return exports;
}
const views = load('./views');
const main = ts.createSourceFile('main.ts', fs.readFileSync('src/main.ts', 'utf8'), ts.ScriptTarget.Latest, true);
const state = main.statements.filter(ts.isVariableStatement).flatMap(statement => [...statement.declarationList.declarations]).find(declaration => declaration.name.getText(main) === 'state').initializer.getText(main);
const readForm = main.statements.find(statement => ts.isFunctionDeclaration(statement) && statement.name?.text === 'readSettingsForm').getText(main);
const inputs = new Map();
const context = { ...views, normalizeTheme: theme => theme, document: { querySelector: selector => inputs.get(selector) ?? null } };
vm.createContext(context);
vm.runInContext(ts.transpileModule(`let state = ${state}; ${readForm}; globalThis.state = state; globalThis.read = readSettingsForm;`, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context);
const html = views.renderApplication(context.state, 'settings', false, 'all');
assert(html.includes("Promote Korea's mission App in chat"));
const toggle = html.match(/<input id="promote-mission-app"[^>]*>/)?.[0];
assert(toggle && toggle.includes('checked'));
assert(html.indexOf('class="mission-promotion-settings"') > html.indexOf('class="app-update-settings"'));
assert(!html.includes('app-update-panel'));
assert(!html.includes('data-test-update-popup'));
const twitchHtml = views.renderApplication(context.state, 'twitch', false, 'all');
assert(!/<details[^>]*\bopen(?:\s|>)/.test(twitchHtml));
assert(!html.includes('data-feedback-key="save-settings"'));
assert(html.includes('<p data-app-version aria-label="Installed app version"></p>'));
assert.match(html, /id="promotion-interval"[^>]*value="60"/);
assert(html.includes('data-twitch-test="promotion" disabled'));
const backend = fs.readFileSync('src-tauri/src/models.rs', 'utf8');
assert(backend.includes("Doing missions? Try Korea"));
assert(html.includes(views.escapeHtml(views.defaultPromotionMessage)));
assert(backend.includes(views.defaultPromotionMessage));
assert(html.includes('class="panel settings-panel mission-promotion-panel"'));
const options = html.match(/<details class="promotion-options[^>]*>/)?.[0];
assert(options && !options.includes(' open'));
const streamerHtml = views.renderApplication(context.state, "streamer", false, "all");
assert(streamerHtml.includes('id="streamer-promotion-enabled"'));
assert(streamerHtml.includes('data-streamer-test="missionPromotion"'));
assert(streamerHtml.includes('value="Marbles - Mission Promotion"'));
inputs.set("#streamer-promotion-enabled", { checked: true });
inputs.set("#streamer-promotion-action", { value: "Custom Promo Action" });
inputs.set('#promote-mission-app', { checked: true });
inputs.set('#promotion-interval', { value: '45' });
context.state.config.twitch.promotionMessage = 'Old saved custom message';
assert(!html.includes('id="promotion-message"'));
assert(html.includes("twitch-message-preview promotion-preview"));
let config = context.read();
assert.equal(config.twitch.promoteMissionApp, true);
assert.equal(config.streamerBot.events.missionPromotion, true);
assert.equal(config.streamerBot.actions.missionPromotion, "Custom Promo Action");
assert.equal(config.twitch.promotionIntervalMinutes, 45);
assert.equal(config.twitch.promotionMessage, undefined);
context.state.config = config;
inputs.clear();
config = context.read(); // Saving on another page preserves promotion settings.
assert.equal(config.twitch.promoteMissionApp, true);
assert.equal(config.twitch.promotionIntervalMinutes, 45);
assert.equal(config.twitch.promotionMessage, undefined);
inputs.set('#promotion-interval', { value: '9999' });
assert.equal(context.read().twitch.promotionIntervalMinutes, 1440);
// Rapid toggles must persist in order, without requiring a form submit.
const saveFunctions = main.statements.filter(statement => ts.isFunctionDeclaration(statement) && ['refreshToggleSaveStatus', 'saveSettingsToggle'].includes(statement.name?.text)).map(statement => statement.getText(main)).join('\n');
const saves = [];
const status = { textContent: '' };
inputs.set('#settings-autosave-status', status);
context.render = () => context.refreshStatus();
context.invoke = (_command, args) => new Promise(resolve => saves.push({ config: args.config, resolve }));
vm.runInContext(ts.transpileModule(`let settingsToggleSaveQueue = Promise.resolve(); let settingsToggleSavesPending = 0; let settingsToggleSaveError = ''; ${saveFunctions}; globalThis.saveToggle = saveSettingsToggle; globalThis.refreshStatus = refreshToggleSaveStatus;`, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context);
inputs.set('#auto-update-check', { checked: false });
context.saveToggle();
inputs.set('#auto-update-check', { checked: true });
context.saveToggle();
await Promise.resolve();
assert.equal(saves.length, 1);
assert.equal(saves[0].config.autoUpdateCheckEnabled, false);
saves[0].resolve({ ...context.state, config: saves[0].config });
for (let turn = 0; turn < 5; turn++) await Promise.resolve();
assert.equal(saves.length, 2);
assert.equal(saves[1].config.autoUpdateCheckEnabled, true);
saves[1].resolve({ ...context.state, config: saves[1].config });
for (let turn = 0; turn < 5; turn++) await Promise.resolve();
assert.equal(status.textContent, 'Toggles save automatically.');
console.log('Promotion settings passed: default on, last in its own panel, grouped updates, closed Twitch accordions, no update test button, fixed message and saved interval.');
